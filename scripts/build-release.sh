#!/usr/bin/env bash
#
# Builds a signed Release build of AutoClicker and packages it as a DMG for a GitHub Release.
#
# Usage (from anywhere; the script works from the repository root):
#
#     scripts/build-release.sh               # Release build, verified, packaged as build/Release/AutoClicker-<version>.dmg
#     scripts/build-release.sh --profiling   # the same Release build, debuggable, with no DMG
#     scripts/build-release.sh NAME=value    # any number of extra build settings, passed on to xcodebuild
#
# Signing: the project's automatic signing with the team's "Apple Development" identity. The app is never ad-hoc
# signed, because macOS ties the Accessibility grant to a stable signature (SPEC §1). It is not notarized either,
# which needs a Developer ID certificate from the paid Apple Developer Program. With one, build with
# `CODE_SIGN_STYLE=Manual CODE_SIGN_IDENTITY="Developer ID Application"`; README.md has the notarization steps.
#
# --profiling keeps the `com.apple.security.get-task-allow` entitlement, so `leaks` and Instruments can attach to the
# app. That entitlement must never ship, so this build gets its own folder (build/Release/Profiling) and no DMG.
#
# Everything is written under build/, which is git-ignored.

set -euo pipefail

readonly lsregister=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister

usage() {
    sed -n 's/^#     //p' "${BASH_SOURCE[0]}"
}

profiling=false
extra_settings=()
for arg in "$@"; do
    case "$arg" in
        --profiling) profiling=true ;;
        -h | --help)
            usage
            exit 0
            ;;
        [A-Z]*=*) extra_settings+=("$arg") ;;
        *)
            echo "error: unknown option: $arg" >&2
            usage >&2
            exit 64
            ;;
    esac
done

# Every path below is relative to the repository root.
cd "$(dirname "${BASH_SOURCE[0]}")/.."

readonly release_dir=build/Release
if $profiling; then
    readonly derived_data="$release_dir/Profiling/DerivedData"
else
    readonly derived_data="$release_dir/DerivedData"
fi
readonly app="$derived_data/Build/Products/Release/AutoClicker.app"

step() {
    printf '\n==> %s\n' "$1"
}

fail() {
    echo "error: $1" >&2
    exit 1
}

# MARK: - Build

xcodebuild_args=(
    -project AutoClicker.xcodeproj
    -scheme AutoClicker
    -configuration Release
    # A generic destination builds every architecture in ARCHS, so the app is universal (Apple Silicon and Intel).
    -destination 'generic/platform=macOS'
    -derivedDataPath "$derived_data"
    -quiet
    # The autogenerated scheme gathers code coverage, and xcodebuild applies that to plain builds too (it sets both
    # settings below to YES). Left on, the shipped binary is instrumented and tries to write a default.profraw file
    # into its working directory on every quit. `-enableCodeCoverage NO` is rejected outside `test`.
    ENABLE_CODE_COVERAGE=NO
    CLANG_COVERAGE_MAPPING=NO
)
if ! $profiling; then
    xcodebuild_args+=(
        # Xcode adds get-task-allow to every build signed with a development identity, which lets any process with
        # the user's rights attach a debugger to the app. A shipped build must not carry it.
        CODE_SIGN_INJECT_BASE_ENTITLEMENTS=NO
        # A secure timestamp from Apple's timestamp server, as notarization requires. Xcode leaves it out of
        # development builds by default. Profiling builds skip it so they also work offline.
        OTHER_CODE_SIGN_FLAGS=--timestamp
    )
fi

# Last, so a setting given on the command line wins over the defaults above. (Bash 3.2, which macOS ships, treats
# expanding an empty array as an unset variable, hence the check.)
if ((${#extra_settings[@]})); then
    xcodebuild_args+=("${extra_settings[@]}")
fi

if $profiling; then
    step "Building the Release configuration for profiling (keeps get-task-allow)"
else
    step "Building the Release configuration"
fi
# `clean` first, so nothing from an earlier build with other settings ends up in the product.
xcodebuild "${xcodebuild_args[@]}" clean build

[[ -d "$app" ]] || fail "the build succeeded but $app does not exist"

# MARK: - Verify the app

step "Verifying the code signature"
codesign --verify --deep --strict --verbose=2 "$app"

signature_info="$(codesign -dvv "$app" 2>&1)"
# The first Authority line is the leaf certificate, the identity that signed the app.
authority="$(awk '/^Authority=/ { sub(/^Authority=/, ""); print; exit }' <<<"$signature_info")"
team="$(awk '/^TeamIdentifier=/ { sub(/^TeamIdentifier=/, ""); print; exit }' <<<"$signature_info")"
timestamp="$(awk '/^Timestamp=/ { sub(/^Timestamp=/, ""); print; exit }' <<<"$signature_info")"

# An ad-hoc signature has no authority and no team, and would reset the Accessibility grant on every build.
[[ -n "$authority" && -n "$team" && "$team" != "not set" ]] || fail "the app is not signed with a certificate"
grep -q 'flags=.*runtime' <<<"$signature_info" || fail "the app is not signed with the Hardened Runtime"

echo "Authority:       $authority"
echo "Team:            $team"
echo "Timestamp:       ${timestamp:-none}"
echo "Architectures:   $(lipo -archs "$app/Contents/MacOS/AutoClicker")"

entitlements="$(codesign -d --entitlements - --xml "$app" 2>/dev/null)"
if grep -q 'com.apple.security.get-task-allow' <<<"$entitlements"; then
    has_get_task_allow=true
else
    has_get_task_allow=false
fi
if $profiling; then
    if ! $has_get_task_allow; then
        fail "the profiling build is missing get-task-allow, so leaks and Instruments cannot attach"
    fi
    echo "Entitlements:    get-task-allow present (profiling build)"
else
    if $has_get_task_allow; then
        fail "the release build carries get-task-allow"
    fi
    [[ -n "$timestamp" ]] || fail "the release build has no secure timestamp"
    echo "Entitlements:    no get-task-allow"
fi

step "Gatekeeper assessment"
# Without notarization Gatekeeper rejects the app; that is expected for now, so the result is shown but not enforced.
spctl -a -vv "$app" 2>&1 || true
echo "(A rejection is expected: the app is signed but not notarized.)"

if $profiling; then
    step "Done"
    echo "App: $PWD/$app"
    echo
    echo "Xcode registered this copy with LaunchServices. When you are done profiling, unregister it so the Dock and"
    echo "Finder keep using the installed app:"
    echo "  $lsregister -u \"$PWD/$app\""
    exit 0
fi

# MARK: - Package

version="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$app/Contents/Info.plist")"
readonly dmg="$release_dir/AutoClicker-$version.dmg"
readonly staging="$release_dir/dmg"

step "Creating $dmg"
rm -rf "$staging"
mkdir -p "$staging"
# ditto keeps the bundle's signature, extended attributes and symlinks intact.
ditto "$app" "$staging/AutoClicker.app"
# The usual drag-to-install layout: the app next to a link to /Applications.
ln -s /Applications "$staging/Applications"
hdiutil create \
    -volname "AutoClicker $version" \
    -srcfolder "$staging" \
    -fs HFS+ \
    -format UDZO \
    -ov \
    -quiet \
    "$dmg"
rm -rf "$staging"
# The build product is only an input to the DMG, but Xcode registered it with LaunchServices. Left registered, it
# competes with the installed app for the bundle ID (a stale registration once broke the Dock icon).
if ! "$lsregister" -u "$PWD/$app"; then
    echo "warning: could not unregister $app from LaunchServices" >&2
fi

step "Signing the DMG"
# The DMG is signed with exactly the certificate that signed the app: its SHA-1 fingerprint names the keychain
# identity, which a common name cannot do once a renewed certificate with the same name is installed.
cert_dir="$(mktemp -d)"
trap 'rm -rf "$cert_dir"' EXIT
codesign -d --extract-certificates="$cert_dir/cert" "$app" 2>/dev/null
identity="$(shasum -a 1 "$cert_dir/cert0" | awk '{ print toupper($1) }')"
codesign --force --sign "$identity" --timestamp "$dmg"
codesign --verify --strict --verbose=2 "$dmg"
spctl -a -t open --context context:primary-signature -vv "$dmg" 2>&1 || true

step "Done"
size_bytes="$(stat -f %z "$dmg")"
echo "DMG:     $PWD/$dmg"
echo "Size:    $(awk -v b="$size_bytes" 'BEGIN { printf "%.1f MB (%d bytes)", b / 1000000, b }')"
echo "SHA-256: $(shasum -a 256 "$dmg" | awk '{ print $1 }')"
